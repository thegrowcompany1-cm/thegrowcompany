/** 슬러그로 게시판 정의 조회 (없으면 undefined) */
export function getBoard(slug: string): Board | undefined {
  return BOARDS.find((b) => b.slug === slug);
}

/** 게시판 글 목록 — 최신순 */
export function getPosts(slug: BoardSlug): Post[] {
  return BOARD_POSTS[slug];
}

/** 게시판 + id 로 단일 글 조회 (없으면 undefined) */
export function getPost(slug: BoardSlug, id: number): Post | undefined {
  return BOARD_POSTS[slug].find((p) => p.id === id);
}

